#!/usr/bin/env python3
"""Train FluxEidosV0-Self: LoRA on PURE self-generated RFT data (no other model's data).

This eliminates the SFT controversy: every training example was generated by
Qwen3.5-9B itself, filtered only by execution (CAD) and rubric (judge).
"""
import json, os, random, subprocess, sys, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
BASE = '/home/exuber/models/qwen3.5-9b-bf16'
OUT = Path(os.environ.get('RFT_OUT', '/home/exuber/models/prsi_self_rft'))
EPOCHS = int(os.environ.get('RFT_EPOCHS', '10'))  # more epochs for small data


def main():
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(BASE, trust_remote_code=True)

    data_f = BENCH / 'runs' / 'self_rft' / 'self_rft_data.jsonl'
    examples = [json.loads(l) for l in data_f.read_text().splitlines() if l.strip()]
    print(f"Self-RFT examples: {len(examples)}", flush=True)

    # Data augmentation: repeat examples (small dataset needs more epochs)
    samples = []
    for e in examples:
        pr = tok.apply_chat_template(e['messages'][:2], tokenize=False,
                                     add_generation_prompt=True, enable_thinking=False)
        samples.append({'prompt': pr, 'text': e['messages'][2]['content'], 'adv': 1.0})

    # Duplicate with slight reordering for effective augmentation
    random.seed(41)
    all_samples = samples * (EPOCHS // 2)  # effective epochs via repetition
    random.shuffle(all_samples)
    print(f"Training samples (with repetition): {len(all_samples)}", flush=True)

    OUT.mkdir(parents=True, exist_ok=True)
    adapter = 'none'
    t0 = time.time()
    for ep in range(1, min(EPOCHS, 5) + 1):  # cap at 5 subprocess epochs
        out_a = str(OUT / f'epoch{ep}')
        job = {
            'adapter': adapter, 'out_adapter': out_a, 'samples': all_samples,
            'lora_r': 32, 'lora_targets': ['q_proj', 'k_proj', 'v_proj', 'o_proj'],
            'core_path': '', 'lr': 1e-4, 'anchor_w': 0.0, 'max_len': 2000,
        }
        job['core_path'] = str(BENCH / 'runs' / 'training_data' / 'sft_v2_core.jsonl')
        jf = OUT / f'job_ep{ep}.json'
        jf.write_text(json.dumps(job))
        r = subprocess.run([sys.executable, '-W', 'ignore', str(HERE / 'rl_train_step_worker.py'), str(jf)],
                           capture_output=True, text=True, timeout=3600)
        line = [l for l in r.stdout.splitlines() if '"status"' in l]
        if not line:
            print(f'epoch {ep} FAILED: {(r.stderr or r.stdout)[-300:]}'); sys.exit(1)
        st = json.loads(line[-1])
        print(f'epoch {ep}: CE={st["pg"]:.4f} over {st["n_pg"]} [{(time.time()-t0)/60:.0f}min]', flush=True)
        adapter = out_a
    print(f'DONE -> {adapter}')


if __name__ == '__main__':
    main()
