ROOT = Path(__file__).resolve().parent.parent
FIG = ROOT / 'paper' / 'figures'
FIG.mkdir(exist_ok=True)

# colorblind-safe, low-saturation palette
C_BLUE, C_ORANGE, C_GREEN, C_RED, C_PURPLE, C_GRAY = \
    '#4878a8', '#d98f4a', '#6a9f58', '#c05a5a', '#8a7ab5', '#9aa0a6'
plt.rcParams.update({
    'font.size': 9, 'axes.spines.top': False, 'axes.spines.right': False,
    'axes.grid': True, 'grid.alpha': 0.25, 'grid.linestyle': '--', 'grid.linewidth': 0.5,
    'figure.dpi': 200,
})


def save(fig, name):
    fig.savefig(FIG / name, dpi=300, bbox_inches='tight')
    plt.close(fig)
    print('saved', name)


# ═══════════════ Fig 1: benchmark schematic ═══════════════
def fig1():
    fig, ax = plt.subplots(figsize=(10.5, 4.4))
    ax.axis('off'); ax.set_xlim(0, 100); ax.set_ylim(-2, 46)

    def box(x, y, w, h, text, fc, ec, fs=8.5, bold=False):
        from matplotlib.patches import FancyBboxPatch
        ax.add_patch(FancyBboxPatch((x, y), w, h, fc=fc, ec=ec, lw=1.2,
                                    boxstyle='round,pad=0.4', mutation_aspect=0.5))
        ax.text(x + w / 2, y + h / 2, text, ha='center', va='center', fontsize=fs,
                fontweight='bold' if bold else 'normal', color='#222')

    def arrow(x1, y1, x2, y2, style='-', color='#555', lw=1.3):
        ax.annotate('', xy=(x2, y2), xytext=(x1, y1),
                    arrowprops=dict(arrowstyle='-|>', color=color, lw=lw, linestyle=style))

    # five-round strip
    rounds = [('R1 scratch\n(new product)', '#eef4fb'), ('R2 adapt\n(bigger product)', '#eef4fb'),
              ('R3 add bay', '#eef4fb'), ('R4 add module\n(combine all)', '#eef4fb'),
              ('R5 shrink\n(keep functions)', '#eef4fb')]
    x = 3
    for i, (t, fc) in enumerate(rounds):
        box(x, 33, 16, 9, t, fc, C_BLUE)
        if i < 4:
            arrow(x + 16.5, 37.5, x + 19.5, 37.5)
        x += 20
    ax.text(2, 43.2, 'five-round cumulative demands', fontsize=9, color='#555', style='italic')

    # generation + CAD chain
    box(8, 20, 20, 8, 'LLM design\n(workstation-csg JSON)', '#fdf6ee', C_ORANGE)
    arrow(18, 32.8, 18, 28.4)
    box(36, 20, 26, 8, 'build123d B-rep execution\nbuild → STEP → re-import', '#f2f7ef', C_GREEN)
    arrow(28.4, 24, 35.6, 24)
    box(68, 20, 26, 8, 'exact geometry metrics\noverlap · envelope', '#f2f7ef', C_GREEN)
    arrow(62.4, 24, 67.6, 24)
    ax.text(81, 15.2, 'invalid → ¥0', fontsize=8, color=C_RED, ha='center')

    # judge + sale
    box(36, 4, 22, 8, 'user-simulation judges\n(3-vendor median)', '#f6f1fa', C_PURPLE)
    arrow(66, 19.6, 58, 12.4)
    box(64, 4, 30, 8, 'sale: rating ≥ 5\n¥100 × speed(<10 s: 1.5× …)', '#eef4fb', C_BLUE)
    arrow(58.4, 8, 63.6, 8)

    # capital loop
    box(3, 4, 26, 8, 'capital registry\nexecuted design → STEP asset', '#fdf6ee', C_ORANGE)
    arrow(16, 12.4, 16, 19.6)          # registry feeds next design
    ax.annotate('', xy=(29, 3.2), xytext=(79, 2.2),                 # sale→registry return path
                arrowprops=dict(arrowstyle='-|>', color=C_ORANGE, lw=1.5,
                                connectionstyle='arc3,rad=0.12'))
    ax.text(97, 43.2, 'validated designs become free, faster capital for later rounds',
            fontsize=8.5, color=C_ORANGE, ha='right', style='italic')
    save(fig, 'fig1_benchmark.png')


